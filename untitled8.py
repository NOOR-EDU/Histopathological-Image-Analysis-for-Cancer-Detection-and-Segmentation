def clean_and_split(image_dir, mask_dir,
                    clean_img_dir,
                    clean_mask_dir,
                    orphan_img_dir,
                    orphan_mask_dir):

    os.makedirs(clean_img_dir, exist_ok=True)
    os.makedirs(clean_mask_dir, exist_ok=True)
    os.makedirs(orphan_img_dir, exist_ok=True)
    os.makedirs(orphan_mask_dir, exist_ok=True)

    images = get_files(image_dir)
    masks = get_files(mask_dir)

    # normalize dictionary (stem → path)
    img_dict = {os.path.splitext(os.path.basename(f.strip()))[0]: f for f in images}
    mask_dict = {os.path.splitext(os.path.basename(f.strip()))[0]: f for f in masks}

    matched = 0
    orphan_images = 0
    orphan_masks = 0

    # 1. process images
    for k, img_path in img_dict.items():

        img_path_clean = img_path.strip()
        mask_path = mask_dict.get(k)

        if mask_path:  # valid pair
            matched += 1

            shutil.copy(img_path_clean, os.path.join(clean_img_dir, os.path.basename(img_path_clean)))
            shutil.copy(mask_path.strip(), os.path.join(clean_mask_dir, os.path.basename(mask_path)))

        else:  # orphan image
            orphan_images += 1
            shutil.copy(img_path_clean, os.path.join(orphan_img_dir, os.path.basename(img_path_clean)))

    # 2. process orphan masks
    for k, mask_path in mask_dict.items():
        if k not in img_dict:
            orphan_masks += 1
            shutil.copy(mask_path.strip(), os.path.join(orphan_mask_dir, os.path.basename(mask_path)))

    print("✅ Matched pairs:", matched)
    print("❌ Orphan images:", orphan_images)
    print("⚠️ Orphan masks:", orphan_masks)

