"""### Grad-CAM Implementation for PCam Model

Grad-CAM (Gradient-weighted Class Activation Mapping) is a technique for producing visual explanations for decisions from a Convolutional Neural Network. It helps understand which parts of an input image are important for the model's classification decision.

The `PCamModel` uses a ResNet34 backbone as its feature extractor (encoder). This is an appropriate architecture for Grad-CAM as it contains convolutional layers whose activations and gradients can be used to generate heatmaps.
"""

import torch
import torch.nn.functional as F
import numpy as np
import cv2

class GradCAM:
    def __init__(self, model, target_layer, device):
        self.model = model
        self.target_layer = target_layer
        self.device = device
        self.model.eval()

        self.gradients = None
        self.activations = None

        # Register hooks
        self.target_layer.register_forward_hook(self.save_activation)
        self.target_layer.register_backward_hook(self.save_gradient)

    def save_activation(self, module, input, output):
        self.activations = output

    def save_gradient(self, module, grad_input, grad_output):
        self.gradients = grad_output[0]

    def __call__(self, input_tensor, target_class=None):
        self.model.zero_grad()

        # Forward pass
        output = self.model(input_tensor.to(self.device))

        if target_class is None:
            # For a single-output binary model, if target_class is not specified,
            # we can infer it from the prediction or default to the positive class.
            # Here, we default to the positive class (1) for Grad-CAM if not provided.
            target_class = 1 if torch.sigmoid(output).item() > 0.5 else 0 # Predicting based on 0.5 threshold

        # Create a gradient tensor for the backward pass
        grad_tensor = torch.zeros_like(output).to(self.device)

        if target_class == 1:
            # For the positive class, we want gradients of the output logit
            grad_tensor.fill_(1.0)
        elif target_class == 0:
            # For the negative class, we want gradients of the inverse of the output logit
            # This can be achieved by negating the gradient for the positive logit
            grad_tensor.fill_(-1.0)
        else:
            raise ValueError("For binary classification with single output, target_class must be 0 or 1.")

        output.backward(gradient=grad_tensor, retain_graph=True)

        # Get gradients and activations
        gradients = self.gradients.cpu().data.numpy()
        activations = self.activations.cpu().data.numpy()

        # Pool the gradients across the channels to get per-channel weights
        weights = np.mean(gradients, axis=(2, 3))[0, :]

        # Weighted combination of activations
        cam = np.zeros(activations.shape[2:], dtype=np.float32)
        for i, w in enumerate(weights):
            cam += w * activations[0, i, :, :]

        # ReLU on the CAM and resize to input image size
        cam = np.maximum(cam, 0)
        # Add a small epsilon to denominator to prevent division by zero for completely black heatmaps
        cam_max = np.max(cam)
        if cam_max == 0:
            cam = np.zeros_like(cam)
        else:
            cam = cam / (cam_max + 1e-8)

        cam = cv2.resize(cam, (input_tensor.shape[3], input_tensor.shape[2]))

        return cam

