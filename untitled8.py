"""### Quantifying Grad-CAM Focus

To quantify the model's Grad-CAM focus, we can analyze the intensity of the generated heatmaps. A simple approach is to calculate the average heatmap intensity in regions where the heatmap values exceed a certain threshold. This provides a numerical metric for how strongly the model's attention is concentrated on specific areas for its predictions.

The following function `quantify_grad_cam_focus` will:
1. Take a batch of images, their true labels, and the generated heatmaps.
2. For each sample, it will determine the predicted class.
3. It will then calculate the mean intensity of the heatmap in areas where the heatmap value is above a specified threshold.
4. These metrics will be collected and presented to give an insight into the model's focus.
"""

def quantify_grad_cam_focus(model, loader, grad_cam_instance, device, heatmap_threshold=0.5, num_samples=10):
    model.eval()
    # Store a list of dictionaries, each containing details for one sample
    all_sample_results = []
    samples_processed = 0

    for imgs, labels in loader:
        if samples_processed >= num_samples:
            break

        for i in range(imgs.shape[0]):
            if samples_processed >= num_samples:
                break

            img_tensor = imgs[i].unsqueeze(0)  # Add batch dimension for single image
            true_label = labels[i].item()

            # Enable gradients for the input tensor for GradCAM calculation
            # Temporarily clone the tensor to allow requires_grad_ for GradCAM
            img_tensor_for_gradcam = img_tensor.clone().detach().requires_grad_(True)


            # Get model prediction for the current image
            logits = model(img_tensor_for_gradcam.to(device))
            pred_prob = torch.sigmoid(logits).item()
            predicted_label = 1 if pred_prob > 0.5 else 0

            # Generate heatmap for the predicted class
            heatmap = grad_cam_instance(img_tensor_for_gradcam, target_class=predicted_label)

            # Quantify focus: average intensity where heatmap is above threshold
            focused_regions_intensity = heatmap[heatmap > heatmap_threshold]
            if focused_regions_intensity.size > 0:
                avg_focus_intensity = np.mean(focused_regions_intensity)
            else:
                avg_focus_intensity = 0.0 # No regions above threshold

            all_sample_results.append({
                "focus_intensity": avg_focus_intensity,
                "img_tensor": img_tensor.cpu(), # Store on CPU to avoid GPU memory issues for many samples
                "true_label": true_label,
                "predicted_label": predicted_label,
                "heatmap": heatmap # Store the raw heatmap
            })

            samples_processed += 1

    # Print summary statistics as before
    positive_focus_intensities = [res["focus_intensity"] for res in all_sample_results if res["predicted_label"] == 1]
    negative_focus_intensities = [res["focus_intensity"] for res in all_sample_results if res["predicted_label"] == 0]

    print(f"Quantified Grad-CAM Focus for {samples_processed} samples:")
    if positive_focus_intensities:
        print(f"  Average focus intensity for positive class predictions: {np.mean(positive_focus_intensities):.4f}")
    else:
        print("  No positive class predictions observed.")

    if negative_focus_intensities:
        print(f"  Average focus intensity for negative class predictions: {np.mean(negative_focus_intensities):.4f}")
    else:
        print("  No negative class predictions observed.")

    return all_sample_results

