def align(x, ref):
    _, _, H, W = ref.shape
    return F.interpolate(x, size=(H, W), mode="bilinear", align_corners=False)

class CryoNuSegDataset(Dataset):

    def __init__(self, img_paths, mask_paths, img_size=256):
        self.img_paths = img_paths
        self.mask_paths = mask_paths
        self.img_size = img_size

    def __len__(self):
        return len(self.img_paths)

    def __getitem__(self, idx):

        img = cv2.imread(self.img_paths[idx])
        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
        img = cv2.resize(img, (self.img_size, self.img_size))
        img = img / 255.0

        # Use PIL to read the mask to ensure all values are preserved
        mask = np.array(Image.open(self.mask_paths[idx]))
        mask = cv2.resize(mask, (self.img_size, self.img_size),
                          interpolation=cv2.INTER_NEAREST)

        mask_bin = (mask > 0).astype(np.float32)

        kernel = np.ones((3, 3), np.uint8)
        boundary = cv2.dilate(mask_bin, kernel) - mask_bin

        img = torch.tensor(img, dtype=torch.float32).permute(2, 0, 1)
        mask_bin = torch.tensor(mask_bin, dtype=torch.float32).unsqueeze(0)
        boundary = torch.tensor(boundary, dtype=torch.float32).unsqueeze(0)

        return img, mask_bin, boundary

