def build_index(image_dir, mask_dir, exts=("png","tif","tiff","jpg","jpeg")):

    image_paths = []
    mask_paths = []

    for ext in exts:
        image_paths.extend(glob(os.path.join(image_dir, f"*.{ext}")))
        mask_paths.extend(glob(os.path.join(mask_dir, f"*.{ext}")))

    image_dict = defaultdict(list)
    mask_dict = defaultdict(list)

    for p in image_paths:
        image_dict[normalize_name(p)].append(p)

    for p in mask_paths:
        mask_dict[normalize_name(p)].append(p)

    return image_dict, mask_dict

def validate_pairs(image_dir, mask_dir):

    image_dict, mask_dict = build_index(image_dir, mask_dir)

    matched = []
    missing_masks = []
    orphan_masks = []

    for key in image_dict:

        if key in mask_dict:
            for img in image_dict[key]:
                for msk in mask_dict[key]:
                    matched.append((img, msk))
        else:
            missing_masks.append(image_dict[key])

    for key in mask_dict:
        if key not in image_dict:
            orphan_masks.append(mask_dict[key])

    print("✅ Total matched pairs:", len(matched))
    print("❌ Images without masks:", len(missing_masks))
    print("⚠️ Orphan masks:", len(orphan_masks))

    return matched, missing_masks, orphan_masks

