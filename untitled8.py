def match_images_and_masks(img_dir, mask_dir, recursive=False):

    # Load paths
    img_paths = glob(os.path.join(img_dir, "*"))
    mask_paths = glob(os.path.join(mask_dir, "**", "*"), recursive=recursive)

    # Build dictionaries
    img_dict = {get_name(p): p for p in img_paths}
    mask_dict = {get_name(p): p for p in mask_paths}

    # Keys
    img_names = set(img_dict.keys())
    mask_names = set(mask_dict.keys())

    # Matches & mismatches
    matched = img_names.intersection(mask_names)
    only_imgs = img_names - mask_names
    only_masks = mask_names - img_names

    print("===================================")
    print(f"Total Images: {len(img_names)}")
    print(f"Total Masks : {len(mask_names)}")
    print(f"Matched Pairs: {len(matched)}")
    print(f"Unmatched Images: {len(only_imgs)}")
    print(f"Unmatched Masks: {len(only_masks)}")
    print("===================================\n")

    # Show some mismatches (debugging)
    if only_imgs:
        print("Example unmatched images:")
        for i, name in enumerate(list(only_imgs)[:10]):
            print("  ", name)

    if only_masks:
        print("\nExample unmatched masks:")
        for i, name in enumerate(list(only_masks)[:10]):
            print("  ", name)

    # Create paired lists
    img_list = []
    mask_list = []

    for name in matched:
        img_list.append(img_dict[name])
        mask_list.append(mask_dict[name])

    return img_list, mask_list


