def scan_dataset(path, exts=("png", "jpg", "jpeg", "tif", "tiff"), limit=500):

    image_paths = []

    for ext in exts:
        image_paths.extend(
            glob(os.path.join(path, f"**/*.{ext}"), recursive=True)
        )

    sizes = []
    corrupted = []

    for p in tqdm(image_paths[:limit]):
        try:
            img = cv2.imread(p, cv2.IMREAD_UNCHANGED)

            if img is None:
                corrupted.append(p)
                continue

            # handle grayscale vs RGB vs multi-channel TIFF
            if len(img.shape) == 2:
                h, w = img.shape
            else:
                h, w = img.shape[:2]

            sizes.append((h, w))

        except:
            corrupted.append(p)

    sizes = np.array(sizes)

    return {
        "total_images": len(image_paths),
        "corrupted": len(corrupted),
        "avg_height": float(np.mean(sizes[:, 0])) if len(sizes) else 0,
        "avg_width": float(np.mean(sizes[:, 1])) if len(sizes) else 0,
        "height_std": float(np.std(sizes[:, 0])) if len(sizes) else 0,
        "width_std": float(np.std(sizes[:, 1])) if len(sizes) else 0,
    }

