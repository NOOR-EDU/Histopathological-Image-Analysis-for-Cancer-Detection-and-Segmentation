            # Ensure the input tensor requires gradients
            img_tensor.requires_grad_(True)

            # Get model prediction for the current image
            logits = model(img_tensor.to(device))
            pred_prob = torch.sigmoid(logits).item()
            predicted_label = 1 if pred_prob > 0.5 else 0

